/**
 * Ответ человека про аналитику: где лежит и что считается ответом.
 *
 * Вынесено из баннера отдельным файлом ровно по одной причине: это
 * единственное место в проекте, где решается, следить за человеком или нет.
 * Такое проверяют тестом (`tests/consent-store.test.mjs`), а тест не поднимает
 * браузер — поэтому хранилище приходит аргументом, а не берётся из `window`.
 */

export const ALLOW = 'yes';
export const DENY = 'no';

/**
 * Ключ с номером редакции. Меняется, когда меняется сам вопрос: если однажды
 * появится второй счётчик с другими данными, старое «да» относилось не к нему,
 * и спросить придётся заново. Тогда — `analytics-consent.2`, и все прежние
 * ответы перестают засчитываться сами.
 */
const KEY = 'analytics-consent';

/**
 * Хранилище бросает в приватном режиме Safari и там, где посетитель запретил
 * сайту хранить данные. Отсутствие ответа — рабочее состояние, поэтому
 * исключение здесь значит «ответа нет», а не «страница сломалась».
 */
export function readChoice(storage) {
  let saved;
  try {
    saved = storage.getItem(KEY);
  } catch {
    return null;
  }
  return saved === ALLOW || saved === DENY ? saved : null;
}

export function writeChoice(storage, choice) {
  try {
    storage.setItem(KEY, choice);
  } catch {
    /* Не сохранилось — значит спросим в следующий раз. Это честнее, чем
       считать несохранённое «да» действующим согласием. */
  }
}

/**
 * Просьбу «не отслеживать» из настроек браузера считаем уже данным ответом:
 * человек сказал это один раз для всех сайтов, и переспрашивать баннером —
 * то же самое, что не услышать.
 */
export function refusesTracking(navigator) {
  return navigator.doNotTrack === '1';
}
