/**
 * Счётчики аналитики — то, о чём спрашивает баннер согласия.
 *
 * Список нужен трём местам сразу: баннеру (спрашивать ли вообще), политике
 * (есть ли о чём писать раздел) и подвалу (показывать ли ссылку «Куки»).
 * Держать это знание в трёх местах — верный способ однажды спросить согласие
 * на счётчик, которого нет, или поставить счётчик, о котором не спросили.
 *
 * Второй счётчик добавляется сюда одной строкой: его номер в список, его
 * загрузку — отдельным файлом рядом с `scripts/metrika.js`. Ни баннер,
 * ни политика, ни подвал об этом не узнают.
 *
 * Номера приходят переменными сборки. Пока переменная пуста, счётчика нет
 * нигде: ни в браузере, ни в политике, ни в вопросе к посетителю.
 */
const IDS = [import.meta.env.PUBLIC_METRIKA_ID];

/** Есть ли на сайте хоть один счётчик — единственное, что нужно знать снаружи. */
export const HAS_ANALYTICS = IDS.some((id) => Boolean(id));
