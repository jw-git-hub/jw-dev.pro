/**
 * Делает блоки кода достижимыми с клавиатуры.
 *
 * `.prose pre` держит длинные строки горизонтальной прокруткой (см.
 * `styles/components/note.css`). Внутри такого блока нет ни одного
 * фокусируемого элемента, поэтому мышью строку дочитать можно, а клавишами —
 * нет: axe ловит это правилом `scrollable-region-focusable`. `tabindex="0"`
 * делает блок остановкой табуляции, и стрелки начинают его листать. Рамку
 * фокуса рисует общее правило `:focus-visible` в `base.css`.
 *
 * Живёт в обработчике markdown, а не в шаблоне статьи: разметку кода создаёт
 * markdown, и в `.astro` этих узлов ещё нет.
 */

/** Плагин Sätteri: правит готовое дерево HTML, отбирая узлы по имени тега. */
export const codeFocusable = {
  name: 'code-focusable',
  element: {
    filter: ['pre'],
    visit(node, ctx) {
      ctx.setProperty(node, 'tabindex', '0');
    },
  },
};
